ПОРЯДОК = ["претензии", "доказательства", "приёмка", "выдача", "возвраты",
           "отправка", "товар", "клиенты", "персонал", "помещение", "локация",
           "оборудование", "деньги", "право", "цикл", "платформа", "доход",
           "человек"]

# Тема, которая измеряет не боль, а вежливость. Убираем из рейтинга.
ЛИШНИЕ = {"Взаимопомощь и обмен опытом"}

БОЛЬ = re.compile("|".join([
    r"проблем", r"не работа", r"не могу", r"не получа", r"не приход", r"не отвеча",
    r"жалоб", r"штраф", r"косяк", r"беда", r"кошмар", r"ужас", r"бесит",
    r"замучил", r"достал", r"что делать", r"как быть", r"подскажите", r"помогите",
    r"почему\b", r"кто сталкивал", r"у кого так", r"караул", r"обидно",
    r"несправедлив", r"вопрос", r"убыт", r"теряю", r"потерял", r"опять",
    r"снова", r"\?"]), re.I)

СЛУЖЕБНОЕ = re.compile(r"^(https?://\S+\s*)+$|^[\s\W\d]*$", re.I)


def main():
    корпус, отчёт = sys.argv[1], sys.argv[2]
    msgs = [json.loads(l) for l in open(корпус, encoding="utf-8")]
    msgs = [m for m in msgs
            if len(m["t"].strip()) >= 12 and not СЛУЖЕБНОЕ.match(m["t"].strip())]
    d = json.load(open(отчёт, encoding="utf-8"))
    d["темы"] = [t for t in d["темы"] if t["тема"] not in ЛИШНИЕ]

    зонты = []
    for раздел in ПОРЯДОК:
        rx = re.compile("|".join(f"(?:{p})" for p in ЗОНТЫ[раздел]), re.I)
        hits = [m for m in msgs if rx.search(m["t"])]
        pain = [m for m in hits if БОЛЬ.search(m["t"])]
        зонты.append({
            "раздел": раздел,
            "имя": ИМЕНА[раздел],
            "msgs": len(hits),
            "authors": len({m["a"] for m in hits}),
            "pain": len(pain),
            "доля_боли": round(len(pain) / len(hits), 3) if hits else 0,
            "помесячно": dict(sorted(collections.Counter(
                m["d"][:7] for m in hits).items())),
            "тем_внутри": sum(1 for t in d["темы"] if t.get("раздел") == раздел),
        })
        print(f'{ИМЕНА[раздел]:<52} {len(hits):>6} · {len({m["a"] for m in hits}):>5} чел')

    d["зонты"] = зонты
    json.dump(d, open(отчёт, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\nтем в рейтинге:", len(d["темы"]))


main()
