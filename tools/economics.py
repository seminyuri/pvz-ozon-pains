def руб(n):
    return шт(n) + " ₽"


def шт(n):
    """Разряды пробелом.

    Отдельной функцией намеренно. Соблазн написать
    f'…{n:,}…'.replace(",", " ") стоил мне уже двух ошибок: соседние строковые
    литералы Python склеивает ДО вызова метода, поэтому replace выкашивает
    запятые из всего текста рядом, а не только из числа.
    """
    return f"{round(n):,}".replace(",", " ")


def главное():
    владельцев = int(ВСЕГО_ТОЧЕК / ТОЧЕК_НА_ВЛАДЕЛЬЦА)
    ряды = []
    for г in ГРУППЫ:
        n = int(владельцев * г["доля"])
        мес_от, мес_до = г["год"][0] / 12, г["год"][1] / 12
        потери = ПРЕТЕНЗИЙ_В_МЕСЯЦ * СРЕДНЯЯ_ПРЕТЕНЗИЯ
        доля_потерь = потери / мес_до * 100 if мес_до else 0
        ряды.append({**г, "владельцев": n, "мес_от": мес_от, "мес_до": мес_до,
                     "потери": потери, "доля_потерь": доля_потерь})
    return владельцев, ряды


